#: Poradi radku uvnitr pipeline: nejdriv, co vybira priznaky, pak klasifikator;
#: pri stejne roli jde napred pocet vybranych priznaku, pak zbytek v poradi kodu.
ROLE_ORDER = {"S": 0, "S+C": 1, "C": 2}
SELECTION_PARAM = "number_of_features"

#: Vyrazy, ktere se nedaji vycislit, ale maji v tabulce ustaleny zapis.
SYMBOLIC = {
    "X.shape[1]": r"\texttt{X.shape[1]}",
    "min(dict(Counter(y)).values()) / len(y)": "minority fraction",
}


def _numeric(node, n_rows, n_cols):
    """Vycisli vyraz meze, pokud obsahuje jen aritmetiku, np.sqrt a X.shape."""
    allowed = (ast.Expression, ast.BinOp, ast.UnaryOp, ast.Constant, ast.Add,
               ast.Sub, ast.Mult, ast.Div, ast.USub, ast.Call, ast.Attribute,
               ast.Name, ast.Subscript, ast.Load, ast.Index)
    for sub in ast.walk(node):
        if not isinstance(sub, allowed):
            return None
        if isinstance(sub, ast.Call) and ast.unparse(sub.func) != "np.sqrt":
            return None
    stub_np = type("np", (), {"sqrt": staticmethod(math.sqrt)})
    stub_x = type("X", (), {"shape": (n_rows, n_cols)})
    try:
        return eval(compile(ast.Expression(node), "<mez>", "eval"),
                    {"__builtins__": {}}, {"np": stub_np, "X": stub_x})
    except Exception:
        return None


def render_bound(node, assignments):
    """LaTeXovy zapis jedne meze prohledavaneho intervalu."""
    if isinstance(node, ast.Name) and node.id in assignments:
        node = assignments[node.id]

    source = ast.unparse(node)
    if source in SYMBOLIC:
        return SYMBOLIC[source]

    if isinstance(node, ast.Constant):
        value = node.value
        return f"{value:g}"

    one = _numeric(node, 1, 1)
    four = _numeric(node, 4, 1)
    if one is not None and four is not None:
        if abs(four - one / 2) < 1e-12:                 # tvar c / sqrt(n)
            return rf"${one:g}/\sqrt{{n}}$"
        if abs(four - one) < 1e-12:                     # na n nezavisi
            return f"{one:g}"
    raise SystemExit(f"neumim prelozit mez: {source}")


def parse_search_space(path, objective):
    """[(slovnik, jmeno parametru, dolni mez, horni mez, skala)] v poradi kodu."""
    tree = ast.parse(common.read_hetero(path))
    func = next((n for n in ast.walk(tree)
                 if isinstance(n, ast.FunctionDef) and n.name == objective), None)
    if func is None:
        raise SystemExit(f"{path}: funkce {objective} tam neni")

    assignments = {}
    for node in ast.walk(func):
        if isinstance(node, ast.Assign) and len(node.targets) == 1:
            if isinstance(node.targets[0], ast.Name):
                assignments[node.targets[0].id] = node.value

    found = []
    for node in ast.walk(func):
        if not (isinstance(node, ast.Assign) and len(node.targets) == 1
                and isinstance(node.targets[0], ast.Name)):
            continue
        owner = node.targets[0].id
        for call in ast.walk(node.value):
            if not (isinstance(call, ast.Call)
                    and isinstance(call.func, ast.Attribute)
                    and call.func.attr in ("suggest_int", "suggest_float")):
                continue
            name = call.args[0].value
            low = render_bound(call.args[1], assignments)
            high = render_bound(call.args[2], assignments)
            log = any(k.arg == "log" and k.value.value for k in call.keywords)
            scale = "log" if log else ("int" if call.func.attr == "suggest_int"
                                       else "float")
            found.append((owner, name, low, high, scale, call.lineno))
    found.sort(key=lambda x: x[-1])
    return [f[:-1] for f in found]


def render(stats=None):
    common.set_table("Tabulka 2")
    groups = []
    for pipeline, path, objective, components in SPEC:
        found = parse_search_space(path, objective)
        unknown = [o for o, *_ in found if o not in components]
        if unknown:
            raise SystemExit(
                f"{path}: {unknown[0]} neni v SPEC -- v kodu pribyl novy parametr")
        found.sort(key=lambda f: (ROLE_ORDER[components[f[0]][1]],
                                  f[1] != SELECTION_PARAM))

        rows = []
        for owner, name, low, high, scale in found:
            component, role = components[owner]
            rows.append([
                pipeline if not rows else "",
                f"{component} ({role})",
                r"\texttt{" + name.replace("_", r"\_") + "}",
                f"{low} -- {high}",
                scale,
            ])
        if not rows:
            raise SystemExit(f"{path}: v {objective} nejsou zadne suggest_* volani")
        groups.append(rows)

    header = [["Pipeline", "Component", "Hyperparameter", "Range", "Scale"]]
    style = [r"\footnotesize", r"\setlength{\tabcolsep}{2.5pt}"]
    body = common.tabular("lllll", header, common.align(groups), style)
    return body, {}

if __name__ == "__main__":
    print(common.write(NAME, render()[0], __file__, SOURCES))
